export const DICT = { zh, en };

export function isLang(x) {
  return LANGS.includes(x);
}

/** 构造一条消息 */
export function msg(k, a) {
  return a === undefined ? { k } : { k, a };
}

export function isMsg(x) {
  return !!x && typeof x === 'object' && typeof x.k === 'string';
}

/** 翻译一个键。没有这个键时显示键本身，方便发现漏翻 */
export function t(lang, key, args) {
  const table = DICT[lang] || DICT[DEFAULT_LANG];
  const s = table[key] ?? DICT[DEFAULT_LANG][key] ?? key;
  if (!args) return s;
  return s.replace(/\{(\w+)\}/g, (all, name) => (name in args ? render(lang, args[name]) : all));
}

/** 把字符串、数字或消息变成要显示的文字 */
export function render(lang, text) {
  if (text === null || text === undefined) return '';
  if (typeof text === 'string') return text;
  if (typeof text === 'number') return String(text);
  if (Array.isArray(text)) return text.map((x) => render(lang, x)).join(t(lang, 'list.sep'));
  if (isMsg(text)) return t(lang, text.k, text.a);
  return String(text);
}

// ---- 存储编码：消息存成带前缀的 JSON，旧数据（普通中文句子）原样保留 ----
const PREFIX = 'i18n:';

export function encodeText(text) {
  if (typeof text === 'string') return text;
  return PREFIX + JSON.stringify(text);
}

export function decodeText(s) {
  if (typeof s !== 'string' || !s.startsWith(PREFIX)) return s ?? '';
  try {
    return JSON.parse(s.slice(PREFIX.length));
  } catch {
    return s;
  }
}

// ---- 日期时间显示：一律按悉尼时间 ----
const WEEK_ZH = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];
const WEEK_EN = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MONTH_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** 悉尼本地日期 YYYY-MM-DD → 2026年12月30日 周三 / Wed 30 Dec 2026 */
export function fmtDate(lang, d) {
  if (!d) return '';
  const [y, m, day] = d.split('-').map(Number);
  const wd = new Date(Date.UTC(y, m - 1, day)).getUTCDay();
  return lang === 'en' ? `${WEEK_EN[wd]} ${day} ${MONTH_EN[m - 1]} ${y}` : `${y}年${m}月${day}日 ${WEEK_ZH[wd]}`;
}

const stampFmt = {};
/** 时间戳（毫秒）→ 悉尼时间 月/日 时:分:秒。不跟电脑时区走 */
export function fmtStamp(lang, ms) {
  const f = (stampFmt[lang] ??= new Intl.DateTimeFormat(lang === 'en' ? 'en-AU' : 'zh-CN', {
    timeZone: TZ, hourCycle: 'h23', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit',
  }));
  return f.format(new Date(ms));
}
